/** Generate transport types and UI constraints from the backend's live schemas. */
import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'
import prettier from 'prettier'

const document = JSON.parse(
  execFileSync(process.env.PYTHON || 'python3', ['../backend/scripts/export_api_contract.py'], {
    encoding: 'utf8',
  }),
)
const schemas = document.components.schemas
const ast = await openapiTS(
  { openapi: document.openapi, info: document.info, paths: {}, components: document.components },
  { propertiesRequiredByDefault: true },
)
const gridParameters = document.paths['/incidents/grid'].get.parameters.filter(
  (parameter) => parameter.in === 'query',
)
const domain = {
  workshopService: document['x-workshop-service'],
  incidentGrid: {
    defaultSort: {
      field: gridParameters.find((parameter) => parameter.name === 'sort_by').schema.default,
      sort: gridParameters.find((parameter) => parameter.name === 'sort_direction').schema.default,
    },
    filterFields: gridParameters
      .map((parameter) => parameter.name)
      .filter(
        (name) => !['page', 'page_size', 'sort_by', 'sort_direction', 'search'].includes(name),
      ),
    searchMaxLength: gridParameters
      .find((parameter) => parameter.name === 'search')
      .schema.anyOf.find((schema) => schema.type === 'string').maxLength,
  },
  statuses: schemas.IncidentStatus.enum,
  priorities: schemas.IncidentPriority.enum,
  categories: schemas.IncidentCategory.enum,
  transitions: document['x-incident-workflow'].transitions,
  adminTransitions: document['x-incident-workflow'].adminTransitions,
  activeStatuses: document['x-incident-workflow'].activeStatuses,
}
const constraints = {}
for (const [name, schema] of Object.entries(schemas)) {
  constraints[name] = {}
  for (const [field, property] of Object.entries(schema.properties || {})) {
    const resolved = property.anyOf?.find((item) => item.type !== 'null') || property
    const rules = Object.fromEntries(
      ['minLength', 'maxLength']
        .filter((rule) => resolved[rule] !== undefined)
        .map((rule) => [rule, resolved[rule]]),
    )
    if (Object.keys(rules).length) constraints[name][field] = rules
  }
  if (!Object.keys(constraints[name]).length) delete constraints[name]
}
const config = await prettier.resolveConfig('.prettierrc.json')
mkdirSync('src/generated', { recursive: true })
for (const [file, source] of [
  ['api.ts', '// Generated by npm run generate:api. Do not edit manually.\n' + astToString(ast)],
  [
    'domain.ts',
    '// Generated by npm run generate:api. Do not edit manually.\n' +
      Object.entries({ ...domain, constraints })
        .map(([key, value]) => `export const ${key} = ${JSON.stringify(value)} as const\n`)
        .join('\n'),
  ],
]) {
  writeFileSync(
    `src/generated/${file}`,
    await prettier.format(source, { ...config, parser: 'typescript' }),
  )
}
